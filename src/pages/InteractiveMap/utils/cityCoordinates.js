/** Look up a city. Returns [lat, lng] or null. */
export function getCityCoords(city) {
  if (!city) return null;
  const key = norm(city);
  return CITY_COORDS[key] || null;
}

/** Look up a "city, country" combo. Useful for variants like
 *  "Funchal, Madeira" which we have as a separate key. */
export function getCityCountryCoords(city, country) {
  if (!city || !country) return getCityCoords(city);
  const combo = `${norm(city)}, ${norm(country)}`;
  return CITY_COORDS[combo] || getCityCoords(city);
}
